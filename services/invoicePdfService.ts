/**
 * Stores the official invoice PDF in memory, disk, and Supabase Storage.
 */
export async function storeInvoicePdf(
    invoiceId: string,
    companyId: string,
    pdfBuffer: Uint8Array,
    invoiceNumber?: string
): Promise<{ storagePath: string; publicUrl?: string }> {
    const safeInvNum = (invoiceNumber || invoiceId || 'document').replace(/[^a-zA-Z0-9_-]/g, '_');
    const fileName = `Invoice_${safeInvNum}_${invoiceId}.pdf`;
    const filePath = `invoices/${fileName}`;

    // 1. Cache in memory for instant delivery
    invoicePdfBufferCache.set(invoiceId, pdfBuffer);

    // 2. Persist to local disk storage
    try {
        const localPath = path.join(invoiceUploadsDir, fileName);
        fs.writeFileSync(localPath, Buffer.from(pdfBuffer));
    } catch (diskErr) {
        console.warn("[storeInvoicePdf] Local disk write warning:", diskErr);
    }

    // 3. Persist to Supabase Storage bucket ('documents' or 'invoices')
    let remotePublicUrl = "";
    try {
        const blob = new Blob([pdfBuffer], { type: 'application/pdf' });
        const { data, error } = await supabaseClient.storage
            .from('documents')
            .upload(filePath, blob, {
                contentType: 'application/pdf',
                upsert: true
            });

        if (!error && data) {
            const { data: urlData } = supabaseClient.storage
                .from('documents')
                .getPublicUrl(filePath);
            if (urlData?.publicUrl) {
                remotePublicUrl = urlData.publicUrl;
            }
        } else if (error) {
            console.warn("[storeInvoicePdf] Supabase storage upload notice:", error.message);
        }
    } catch (storageErr) {
        console.warn("[storeInvoicePdf] Supabase storage error:", storageErr);
    }

    return {
        storagePath: filePath,
        publicUrl: remotePublicUrl
    };
}

