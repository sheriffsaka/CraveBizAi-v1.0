export async function getStoredInvoicePdf(invoiceId: string, companyId?: string): Promise<Uint8Array | null> {
    // 1. Check in-memory cache
    if (invoicePdfBufferCache.has(invoiceId)) {
        return invoicePdfBufferCache.get(invoiceId)!;
    }

    // 2. Check local disk
    try {
        if (fs.existsSync(invoiceUploadsDir)) {
            const files = fs.readdirSync(invoiceUploadsDir);
            const matchedFile = files.find(f => f.includes(invoiceId));
            if (matchedFile) {
                const diskBuffer = fs.readFileSync(path.join(invoiceUploadsDir, matchedFile));
                const uint8 = new Uint8Array(diskBuffer);
                invoicePdfBufferCache.set(invoiceId, uint8);
                return uint8;
            }
        }
    } catch (diskErr) {
        console.warn("[getStoredInvoicePdf] Disk read warning:", diskErr);
    }

    // 3. Check Supabase Storage
    try {
        const filePath = `invoices/Invoice_${invoiceId}.pdf`;
        const { data, error } = await supabaseClient.storage
            .from('documents')
            .download(filePath);
        if (!error && data) {
            const arrBuf = await data.arrayBuffer();
            const uint8 = new Uint8Array(arrBuf);
            invoicePdfBufferCache.set(invoiceId, uint8);
            return uint8;
        }
    } catch (storageErr) {
        // Fall through to null so caller can generate from DB
    }

    return null;
}

/**
 * Invalidates the cached PDF when an invoice is edited or updated.
 */
export function invalidateInvoicePdfCache(invoiceId: string): void {
    invoicePdfBufferCache.delete(invoiceId);
    invoiceDataCache.delete(invoiceId);
    try {
        if (fs.existsSync(invoiceUploadsDir)) {
            const files = fs.readdirSync(invoiceUploadsDir);
            for (const f of files) {
                if (f.includes(invoiceId)) {
                    fs.unlinkSync(path.join(invoiceUploadsDir, f));
                }
            }
        }
    } catch (e) {
        // Safe ignore
    }
}
